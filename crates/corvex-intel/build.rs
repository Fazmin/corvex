//! Build script — embeds the vendored Wappalyzer dataset into the
//! binary via `include_str!`, so the running app never has to find
//! the files on disk.
//!
//! If `data/wappalyzer/` is absent at build time (e.g. before the
//! refresh script is run), the generated module exposes an empty
//! dataset and the runtime falls back to the compile-time seed.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let dest = out_dir.join("wappalyzer_embedded.rs");

    let data_root = manifest_dir.join("data").join("wappalyzer");

    // Re-run if the dataset directory is touched. Watching the parent
    // catches the "the directory gets populated later" case.
    println!("cargo:rerun-if-changed={}", data_root.display());

    let mut out = fs::File::create(&dest).expect("create embedded module");

    writeln!(out, "// Auto-generated by build.rs — do not edit.").unwrap();
    writeln!(out).unwrap();

    // --- categories.json (optional) -------------------------------------
    let cats = data_root.join("categories.json");
    if cats.is_file() {
        println!("cargo:rerun-if-changed={}", cats.display());
        writeln!(
            out,
            "pub const EMBEDDED_CATEGORIES: Option<&str> = Some(include_str!(r#\"{}\"#));",
            cats.display()
        )
        .unwrap();
    } else {
        writeln!(out, "pub const EMBEDDED_CATEGORIES: Option<&str> = None;").unwrap();
    }

    // --- technologies/*.json --------------------------------------------
    writeln!(
        out,
        "pub const EMBEDDED_TECHNOLOGIES: &[(&str, &str)] = &["
    )
    .unwrap();

    let tech = data_root.join("technologies");
    if tech.is_dir() {
        println!("cargo:rerun-if-changed={}", tech.display());
        let mut files: Vec<PathBuf> = fs::read_dir(&tech)
            .unwrap()
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("json"))
            .collect();
        files.sort();
        for path in files {
            println!("cargo:rerun-if-changed={}", path.display());
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            writeln!(
                out,
                "    ({name:?}, include_str!(r#\"{disp}\"#)),",
                name = name,
                disp = path.display()
            )
            .unwrap();
        }
    }
    writeln!(out, "];").unwrap();

    write_stub_if_missing(&manifest_dir);
}

/// Create an empty placeholder at `data/wappalyzer/` if the refresh
/// script hasn't been run yet. Prevents the rerun-if-changed watch
/// from failing on a non-existent path across some Cargo versions.
fn write_stub_if_missing(manifest_dir: &Path) {
    let root = manifest_dir.join("data").join("wappalyzer");
    if !root.exists() {
        let _ = fs::create_dir_all(&root);
    }
}
